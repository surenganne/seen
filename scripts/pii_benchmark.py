"""Precision and recall per PII type on the labelled corpus. Writes docs/pii-benchmark.md.

--check: recompute and fail if any type drops below the committed numbers, or a high-confidence
type misses its target (95% precision, 90% recall; adjustable by the owner here).
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

from seen_core.pii.detect import scan

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "tests/fixtures/pii_corpus/corpus.jsonl"
DOC = ROOT / "docs/pii-benchmark.md"
HIGH = {"aadhaar", "card", "iban", "secret"}
TARGET_P, TARGET_R = 0.95, 0.90


def measure() -> dict[str, dict[str, float]]:
    tp, fp, fn = Counter(), Counter(), Counter()
    for line in CORPUS.read_text().splitlines():
        row = json.loads(line)
        got = {f.type for f in scan(row["text"], min_confidence="medium")}
        want = set(row["labels"])
        for t in got & want:
            tp[t] += 1
        for t in got - want:
            fp[t] += 1
        for t in want - got:
            fn[t] += 1
    out = {}
    for t in sorted(set(tp) | set(fp) | set(fn)):
        p = tp[t] / (tp[t] + fp[t]) if tp[t] + fp[t] else 1.0
        r = tp[t] / (tp[t] + fn[t]) if tp[t] + fn[t] else 1.0
        out[t] = {"precision": round(p, 4), "recall": round(r, 4), "tp": tp[t], "fp": fp[t], "fn": fn[t]}
    return out


def render(m: dict[str, dict[str, float]]) -> str:
    lines = ["# PII benchmark", "", "Generated by `scripts/pii_benchmark.py` from `tests/fixtures/pii_corpus/corpus.jsonl` "
             "(synthetic data only). Detector: tier 1 regex + validators, findings at medium confidence or higher.", "",
             f"High-confidence types ({', '.join(sorted(HIGH))}) must reach {TARGET_P:.0%} precision and {TARGET_R:.0%} recall.", "",
             "| Type | Precision | Recall | TP | FP | FN |", "|---|---|---|---|---|---|"]
    for t, x in m.items():
        lines.append(f"| {t}{' (high)' if t in HIGH else ''} | {x['precision']:.1%} | {x['recall']:.1%} | {x['tp']} | {x['fp']} | {x['fn']} |")
    lines += ["", "Regex finds structured identifiers. It does not find names, addresses or free-text health details.", "",
              "**Read with care:** the corpus is synthetic and was written alongside the detectors, so these numbers show the "
              "detectors handle the cases we thought of. Real-world precision is measured at the Phase 4B exit, when the owner "
              "reviews 50 real findings (target: 80% real).", "",
              "<!-- metrics", json.dumps(m, indent=1, sort_keys=True), "-->", ""]
    return "\n".join(lines)


def main() -> None:
    m = measure()
    if "--check" not in sys.argv:
        DOC.write_text(render(m))
        print(render(m))
        return
    committed = json.loads(re.search(r"<!-- metrics\n(.*?)\n-->", DOC.read_text(), re.S).group(1))
    bad = []
    for t, x in m.items():
        if t in HIGH and (x["precision"] < TARGET_P or x["recall"] < TARGET_R):
            bad.append(f"{t}: below target ({x['precision']:.1%} / {x['recall']:.1%})")
        old = committed.get(t)
        if old and (x["precision"] < old["precision"] or x["recall"] < old["recall"]):
            bad.append(f"{t}: dropped from {old['precision']:.1%}/{old['recall']:.1%} to {x['precision']:.1%}/{x['recall']:.1%}")
    if bad:
        sys.exit("PII benchmark regressed:\n  " + "\n  ".join(bad))
    print("PII benchmark ok")


if __name__ == "__main__":
    main()
